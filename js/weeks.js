function weekTrimester(w) {
  if (w <= 13) return "الثلث الأول";
  if (w <= 27) return "الثلث الثاني";
  return "الثلث الثالث";
}

function renderWeek(w) {
  const data = WEEKS[w - 1];
  document.getElementById("wk-fruit").textContent = data.fruit;
  document.getElementById("wk-title").textContent = "الأسبوع " + data.w + " — بحجم " + data.size;
  document.getElementById("wk-trimester").textContent = weekTrimester(data.w);
  document.getElementById("wk-len").textContent = data.len;
  document.getElementById("wk-wt").textContent = data.wt;
  document.getElementById("wk-desc").textContent = data.desc;
  document.getElementById("wk-tip").textContent = data.tip;

  document.querySelectorAll(".week-chip").forEach((chip) => {
    chip.classList.toggle("active", Number(chip.dataset.week) === w);
  });
}

const selector = document.getElementById("week-selector");
if (selector) {
  for (let i = 1; i <= 40; i++) {
    const btn = document.createElement("button");
    btn.className = "week-chip";
    btn.dataset.week = i;
    btn.textContent = i;
    btn.addEventListener("click", () => {
      renderWeek(i);
      history.replaceState(null, "", "#week-" + i);
    });
    selector.appendChild(btn);
  }

  const hashWeek = parseInt((location.hash.match(/week-(\d+)/) || [])[1], 10);
  renderWeek(hashWeek >= 1 && hashWeek <= 40 ? hashWeek : 12);
}
