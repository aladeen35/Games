# -*- coding: utf-8 -*-
"""قواعد استنتاج التخصص المؤهِّل من اسم الكلية أو البرنامج.

التخصصات المعتمدة:
  علمي : أحياء، هندسية، حاسوب
  أدبي : دراسات إسلامية، أدب إنجليزي، فنون وتصميم

التطبيع يوحّد الهمزات والتاء المربوطة ويحذف «ال» التعريف، ثم تُطبَّق القواعد
بالترتيب وأول قاعدة تُطابق هي المعتمدة. الترتيب مقصود: الأدق أولاً.
"""
import re

SCI = ["أحياء", "هندسية", "حاسوب"]
ART = ["دراسات إسلامية", "أدب إنجليزي", "فنون وتصميم"]
BOTH = SCI + ART


def fold_letters(s):
    """توحيد صور الحروف فقط — آمن على رموز التعبير النمطي."""
    s = re.sub(r"[إأآا]", "ا", s)
    return s.replace("ى", "ي").replace("ة", "ه").replace("ؤ", "و").replace("ئ", "ي")


def normalize(s):
    """تطبيع النص المُختبَر: توحيد الحروف، حذف «ال» التعريف، وتنظيف الرموز."""
    s = fold_letters(s)
    s = re.sub(r"\bال", "", s)          # حذف «ال» التعريف من كل كلمة
    s = re.sub(r"[()\-–_]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


RULES = [
    # ---- قسم معلن صراحةً في اسم البرنامج ----
    (r"قسم ادبي|شعبه ادبيه|ادبي$", ART),
    (r"قسم علمي|شعبه علميه|علمي$", SCI),

    # ---- طبية وصحية ----
    (r"اسنان", ["أحياء"]),
    (r"صيدل", ["أحياء"]),
    (r"بيطر", ["أحياء"]),
    (r"مختبر|تحاليل", ["أحياء"]),
    (r"تمريض|قباله", ["أحياء"]),
    (r"علاج طبيعي|اشعه|تخدير|بصريات|سمعيات|اطراف صناعيه|طواري|اسعاف", ["أحياء"]),
    (r"تغذيه|اغذيه|صحه عامه|صحه بيئه|صحه مجتمع|صحيه", ["أحياء"]),
    (r"(?:^|\s|و)طب(?!يع)", ["أحياء"]),

    # ---- إعلام (قبل الهندسة حتى لا يُسحب «اتصال» إليها) ----
    (r"اعلام|صحاف|علاقات عامه|علوم اتصال|اتصال جماهيري", BOTH),

    # ---- زراعية وموارد طبيعية ----
    (r"هندسه زراعيه|هندسه اغذيه|هندسه نظم زراعيه", ["هندسية", "أحياء"]),
    (r"زراع|غابات|مراعي|حيوان|سمكيه|اسماك|بحار|مصائد|موارد طبيعيه|بيئ|حياه بريه|صحراوي",
     ["أحياء"]),

    # ---- حاسوب ----
    (r"حاسوب|حاسبات|تقانه معلومات|تقنيه معلومات|نظم معلومات|برمج|ذكاء اصطناعي|امن سيبراني|شبكات|معلوماتيه",
     ["حاسوب", "هندسية"]),

    # ---- هندسية وعلوم أرض ----
    (r"عماره|معماري|تخطيط عمراني|تخطيط حضري|حضري|مساحه", ["هندسية"]),
    (r"معادن|علوم ارض|ثروات معدنيه|جيولوج|بترول|نفط|تعدين", ["هندسية"]),
    (r"هندس|تقاني|تكنولوجيا|طاقه|كهرباء|ميكانيك|الكترون|اتصالات|نسيج|غزل", ["هندسية", "حاسوب"]),

    # ---- علوم بحتة ----
    (r"قسم احياء|علوم حياه|كيمياء حيويه|احياء دقيقه|نبات|علم حيوان|احياء|احيائ|تقانه حيويه",
     ["أحياء"]),
    (r"قسم رياضيات|قسم فيزياء|رياضيات|احصاء|فيزياء|فلك|ارصاد|ليزر|طاقات متجدده",
     ["هندسية", "حاسوب"]),
    (r"كيمياء", ["أحياء", "هندسية"]),
    (r"^كليه علوم$|علوم تطبيقيه|علوم بحته|^علوم ", SCI),

    # ---- شريعة ولغة عربية ----
    (r"شريع|اصول دين|قران|دعوه|فقه|حديث|اسلامي|لغه عربيه|عربيه|فلسفه|اديان|عقيده",
     ["دراسات إسلامية"]),

    # ---- لغات ----
    (r"لغات|السن|ترجمه|لغه انجليزيه|ادب انجليزي|انجليزيه|فرنسيه", ["أدب إنجليزي", "دراسات إسلامية"]),

    # ---- فنون ----
    (r"فنون|تصميم|موسيق|دراما|مسرح|خزف|نحت|جرافيك", ["فنون وتصميم", "أدب إنجليزي", "دراسات إسلامية"]),

    # ---- إنسانية وإدارية (تقبل المسارين عادةً) ----
    (r"قانون|شرطه|عداله|حقوق", BOTH),
    (r"اقتصاد|ادار|تجار|محاسب|تمويل|مصرفي|بنوك|اعمال|تسويق|موارد بشريه|سياحه|فندق", BOTH),
    (r"تربيه|معلم", BOTH),
    (r"اداب|اجتماع|نفس|تاريخ|جغرافيا|علوم سياسيه|خدمه اجتماعيه|انثروبولوجيا|مكتبات|وثائق|اثار",
     BOTH),
    (r"تنمو|تنمي|مجتمع|ريفي|سكان|دراسات", BOTH),
]

# تُطبَّق على النمط صور الحروف فقط، فتبقى رموز التعبير النمطي كما هي.
NORM_RULES = [(re.compile(fold_letters(p)), s) for p, s in RULES]


def specs_for(name):
    """يُرجع (قائمة التخصصات، هل طابقت قاعدة)."""
    n = normalize(name)
    for rx, specs in NORM_RULES:
        if rx.search(n):
            return specs, True
    return [], False
